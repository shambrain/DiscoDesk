[CmdletBinding()]
param(
    [ValidateSet('Doctor', 'Check', 'BuildDebug', 'RebuildDebug', 'BuildSymbols', 'Test', 'OpenIDE', 'DeveloperShell')]
    [string]$Action = 'Doctor'
)

$ErrorActionPreference = 'Stop'
$script:RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$script:CargoBin = Join-Path $env:USERPROFILE '.cargo\bin'

function Invoke-External {
    param([Parameter(Mandatory = $true)][string]$FilePath, [string[]]$ArgumentList = @())
    & $FilePath @ArgumentList
    if ($LASTEXITCODE -ne 0) {
        throw ("Command failed with exit code {0}: {1} {2}" -f $LASTEXITCODE, $FilePath, ($ArgumentList -join ' '))
    }
}

function Get-VsWherePath {
    $programFilesX86 = [Environment]::GetEnvironmentVariable('ProgramFiles(x86)')
    $candidate = Join-Path $programFilesX86 'Microsoft Visual Studio\Installer\vswhere.exe'
    if (Test-Path -LiteralPath $candidate) { return $candidate }
    $command = Get-Command vswhere.exe -ErrorAction SilentlyContinue
    if ($command) { return $command.Source }
    throw 'vswhere.exe was not found. Repair Visual Studio Installer or install Visual Studio Build Tools 2026.'
}

function Get-StableVs18Path {
    $vswhere = Get-VsWherePath
    $paths = @(& $vswhere -all -products '*' -version '[18.0,19.0)' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath 2>$null | Where-Object { $_ -and (Test-Path -LiteralPath $_) })
    if ($paths.Count -eq 0) {
        throw 'No stable Visual Studio 18.x installation with the MSVC x64/x86 component was found. The Insiders IDE may be installed, but a stable Build Tools 2026 toolchain is preferred.'
    }
    $buildTools = @($paths | Where-Object { $_ -match '[\\/]BuildTools[\\/]?$' })
    if ($buildTools.Count -gt 0) { return $buildTools[0].Trim() }
    return $paths[0].Trim()
}

function Import-VsEnvironment {
    $vsPath = Get-StableVs18Path
    $devCmd = Join-Path $vsPath 'Common7\Tools\VsDevCmd.bat'
    if (-not (Test-Path -LiteralPath $devCmd)) { throw "VsDevCmd.bat is missing from selected Visual Studio installation: $vsPath" }

    $commandLine = '""{0}" -no_logo -arch=x64 -host_arch=x64 && set"' -f $devCmd
    $environmentLines = @(& $env:ComSpec /d /s /c $commandLine)
    if ($LASTEXITCODE -ne 0) { throw "VsDevCmd.bat failed with exit code $LASTEXITCODE." }

    foreach ($line in $environmentLines) {
        if ($line -match '^([^=]+)=(.*)$') {
            [Environment]::SetEnvironmentVariable($matches[1], $matches[2], 'Process')
        }
    }
    if (Test-Path -LiteralPath $script:CargoBin) { $env:PATH = $script:CargoBin + ';' + $env:PATH }
    $script:VsPath = $vsPath
    $script:VsDevCmd = $devCmd
}

function Get-CommunityIdePath {
    $vswhere = Get-VsWherePath
    $paths = @(& $vswhere -all -prerelease -products Microsoft.VisualStudio.Product.Community -property installationPath 2>$null | Where-Object { $_ -and (Test-Path -LiteralPath $_) })
    foreach ($path in $paths) {
        $devenv = Join-Path $path 'Common7\IDE\devenv.exe'
        if (Test-Path -LiteralPath $devenv) { return $devenv }
    }
    return $null
}

function Assert-EngineEntryPoint {
    $entryPoint = Join-Path $script:RepoRoot 'apps\discodesk-engine\src\main.rs'
    if (-not (Test-Path -LiteralPath $entryPoint)) {
        throw @'
The current checkout does not contain apps/discodesk-engine/src/main.rs, although apps/discodesk-engine/Cargo.toml declares it as the binary path.
No placeholder entry point will be generated by this Visual Studio integration.
Commit or pull the real Gate 0 engine scaffold before building or debugging the engine.
'@
    }
}

function Invoke-Cargo {
    param([Parameter(Mandatory = $true)][string[]]$Arguments)
    $cargo = Get-Command cargo.exe -ErrorAction SilentlyContinue
    if (-not $cargo) {
        $candidate = Join-Path $script:CargoBin 'cargo.exe'
        if (Test-Path -LiteralPath $candidate) {
            $env:PATH = $script:CargoBin + ';' + $env:PATH
            $cargo = Get-Command cargo.exe -ErrorAction SilentlyContinue
        }
    }
    if (-not $cargo) {
        throw 'Cargo was not found. Expected rustup-managed tools under %USERPROFILE%\.cargo\bin. The project rust-toolchain.toml pins the toolchain; this script does not install or replace Rust.'
    }
    Invoke-External -FilePath $cargo.Source -ArgumentList $Arguments
}

function Show-Doctor {
    Write-Host ''
    Write-Host '=== DiscoDesk Visual Studio environment ===' -ForegroundColor Cyan
    $vsPath = Get-StableVs18Path
    $devCmd = Join-Path $vsPath 'Common7\Tools\VsDevCmd.bat'
    Write-Host ("Selected stable VS 18.x toolchain: {0}" -f $vsPath)
    if (-not (Test-Path -LiteralPath $devCmd)) { throw "Missing VsDevCmd.bat: $devCmd" }
    Import-VsEnvironment
    Write-Host ("VsDevCmd: {0}" -f $script:VsDevCmd)

    foreach ($tool in @('cl.exe', 'link.exe', 'msbuild.exe', 'cmake.exe')) {
        $found = Get-Command $tool -ErrorAction SilentlyContinue
        if ($found) { Write-Host ("FOUND  {0}: {1}" -f $tool, $found.Source) -ForegroundColor Green }
        else { Write-Host ("MISSING {0}" -f $tool) -ForegroundColor Yellow }
    }

    Write-Host ''
    Write-Host 'Windows SDK Include versions:'
    $programFilesX86 = [Environment]::GetEnvironmentVariable('ProgramFiles(x86)')
    $sdkInclude = Join-Path $programFilesX86 'Windows Kits\10\Include'
    if (Test-Path -LiteralPath $sdkInclude) {
        Get-ChildItem -LiteralPath $sdkInclude -Directory | ForEach-Object { Write-Host ('  ' + $_.Name) }
    } else {
        Write-Host '  Windows SDK include directory not found.' -ForegroundColor Yellow
    }

    Write-Host ''
    $rustc = Get-Command rustc.exe -ErrorAction SilentlyContinue
    $cargo = Get-Command cargo.exe -ErrorAction SilentlyContinue
    if ($rustc) {
        Write-Host ('Rust: ' + (& $rustc.Source --version)) -ForegroundColor Green
        $hostLine = (& $rustc.Source -Vv | Select-String '^host:')
        if ($hostLine) { Write-Host ('Rust host: ' + $hostLine.ToString().Trim()) }
    } else {
        Write-Host 'Rust compiler not found on PATH.' -ForegroundColor Red
    }
    if ($cargo) { Write-Host ('Cargo: ' + (& $cargo.Source --version)) -ForegroundColor Green }
    else { Write-Host 'Cargo not found on PATH.' -ForegroundColor Red }

    $webViewKeys = @(
        'HKLM:\SOFTWARE\WOW6432Node\Microsoft\EdgeUpdate\Clients\{F3017226-FE2A-4295-8BDF-00C3A9A7E4C5}',
        'HKLM:\SOFTWARE\Microsoft\EdgeUpdate\Clients\{F3017226-FE2A-4295-8BDF-00C3A9A7E4C5}'
    )
    $webView = $null
    foreach ($key in $webViewKeys) {
        $item = Get-ItemProperty -LiteralPath $key -ErrorAction SilentlyContinue
        if ($item -and $item.pv) { $webView = $item.pv; break }
    }
    if ($webView) { Write-Host ("WebView2 Runtime: {0}" -f $webView) -ForegroundColor Green }
    else { Write-Host 'WebView2 Runtime registry entry not found; verify Evergreen Runtime separately.' -ForegroundColor Yellow }

    $ide = Get-CommunityIdePath
    if ($ide) { Write-Host ("Community IDE: {0}" -f $ide) -ForegroundColor Green }
    else { Write-Host 'Visual Studio Community IDE executable not found. Build Tools can still compile the workspace.' -ForegroundColor Yellow }

    $engineSource = Join-Path $script:RepoRoot 'apps\discodesk-engine\src\main.rs'
    if (Test-Path -LiteralPath $engineSource) { Write-Host 'Engine entry point: present' -ForegroundColor Green }
    else { Write-Host 'Engine entry point: missing in this checkout; Visual Studio launch profiles are staged for the eventual binary.' -ForegroundColor Yellow }

    Write-Host ''
    Write-Host 'Doctor completed. Tool discovery is not a successful Cargo build or Studio runtime test.'
}

try {
    Push-Location $script:RepoRoot
    if ($Action -eq 'Doctor') {
        Show-Doctor
        exit 0
    }

    Import-VsEnvironment
    switch ($Action) {
        'Check' {
            $powershell = Get-Command powershell.exe -ErrorAction SilentlyContinue
            if (-not $powershell) { throw 'Windows PowerShell (powershell.exe) was not found.' }
            Invoke-External -FilePath $powershell.Source -ArgumentList @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', (Join-Path $script:RepoRoot 'scripts\check.ps1'))
        }
        'BuildDebug' {
            Assert-EngineEntryPoint
            Invoke-Cargo -Arguments @('build', '-p', 'discodesk-engine', '--bin', 'discodesk-engine')
        }
        'RebuildDebug' {
            Assert-EngineEntryPoint
            Invoke-Cargo -Arguments @('clean', '-p', 'discodesk-engine')
            Invoke-Cargo -Arguments @('build', '-p', 'discodesk-engine', '--bin', 'discodesk-engine')
        }
        'BuildSymbols' {
            Assert-EngineEntryPoint
            Invoke-Cargo -Arguments @('build', '-p', 'discodesk-engine', '--bin', 'discodesk-engine', '--profile', 'release-with-symbols')
        }
        'Test' {
            Invoke-Cargo -Arguments @('test', '--workspace', '--all-features')
        }
        'OpenIDE' {
            $ide = Get-CommunityIdePath
            if (-not $ide) { throw 'Visual Studio Community IDE executable was not found. Build Tools alone do not include devenv.exe.' }
            Start-Process -FilePath $ide
            Write-Host 'Visual Studio started. Choose File > Open > Folder and select the DiscoDesk repository root.'
        }
        'DeveloperShell' {
            Start-Process -FilePath (Join-Path $PSHOME 'powershell.exe') -WorkingDirectory $script:RepoRoot -ArgumentList @('-NoExit')
            Write-Host 'Opened PowerShell inheriting the initialized VS x64 environment and Cargo PATH.'
        }
    }
} catch {
    Write-Host ''
    Write-Host $_.Exception.Message -ForegroundColor Red
    exit 1
} finally {
    Pop-Location
}
